def dump(path: Path, docs):
    path.parent.mkdir(parents=True, exist_ok=True)
    docs = docs if isinstance(docs, list) else [docs]
    path.write_text(
        "# Generated by deploy/k8s/generate.py — edit the generator, not this file.\n"
        + "---\n".join(yaml.dump(d, sort_keys=False, width=120) for d in docs)
    )


