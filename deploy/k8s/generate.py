def infra(name, image, port, env=None, extra_ports=(), memory="512Mi", args=None, probe=None, volume=None):
    c = {"name": name, "image": image, "ports": [{"name": "main", "containerPort": port}] + [{"name": f"p{p}", "containerPort": p} for p in extra_ports],
         "env": [{"name": k, "value": v} for k, v in (env or {}).items()],
         "resources": {"requests": {"cpu": "50m", "memory": "128Mi"}, "limits": {"memory": memory}}}
    if args:
        c["args"] = args
    if probe:
        c["readinessProbe"] = probe
    pod = {"metadata": {"labels": {"app.kubernetes.io/name": name}}, "spec": {"enableServiceLinks": False, "containers": [c]}}
    pvc = None
    if volume:
        # PVC (kind: local-path), not emptyDir: a config change recreates the pod and must not wipe
        # the vector index or the catalog.
        c["volumeMounts"] = [{"name": "data", "mountPath": volume, **({"subPath": "data"} if name == "postgres" else {})}]
        pod["spec"]["volumes"] = [{"name": "data", "persistentVolumeClaim": {"claimName": f"{name}-data"}}]
        pvc = {"apiVersion": "v1", "kind": "PersistentVolumeClaim", "metadata": {"name": f"{name}-data"},
               "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "5Gi"}}}}
    dep = {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": {"name": name},
           "spec": {"replicas": 1, "selector": {"matchLabels": {"app.kubernetes.io/name": name}}, "strategy": {"type": "Recreate"}, "template": pod}}
    svc = {"apiVersion": "v1", "kind": "Service", "metadata": {"name": name},
           "spec": {"selector": {"app.kubernetes.io/name": name}, "ports": [{"name": "main", "port": port, "targetPort": port}] + [{"name": f"p{p}", "port": p, "targetPort": p} for p in extra_ports]}}
    return [dep, svc] + ([pvc] if pvc else [])


