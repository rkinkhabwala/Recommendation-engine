def labels(name):
    return {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": "recsys"}


def container(name, s):
    cpus = max(2, math.ceil(float(s["cpu"].rstrip("m")) / (1000 if s["cpu"].endswith("m") else 1)) * 2)
    opts = s.get("java_opts", "-XX:MaxRAMPercentage=60 -XX:MaxDirectMemorySize=96m -XX:+UseG1GC -XX:MaxGCPauseMillis=20 -XX:+ExitOnOutOfMemoryError")
    # Size JVM ergonomics (GC/JIT threads, netty loops, virtual-thread carriers) to ~2x the CPU
    # request: with no CPU limit the JVM would otherwise size everything for the whole node.
    # The serving API is exempt: capping it also cut G1's parallel GC threads and lengthened young
    # pauses past the latency budget under load (docs/load-test-results.md).
    if not s.get("public_latency_critical"):
        opts += f" -XX:ActiveProcessorCount={cpus}"
    env = [{"name": "JAVA_OPTS", "value": opts}]
    # glibc keeps up to 8 x CPUs malloc arenas; with many native-allocating threads (netty, gRPC,
    # RocksDB) that was ~250 MB of untracked RSS per pod and OOM kills under load. Two is plenty.
    env.append({"name": "MALLOC_ARENA_MAX", "value": "2"})
    env += [{"name": k, "value": v} for k, v in s.get("env", {}).items()]
    if s.get("stateful"):
        env.append({"name": "HOSTNAME", "valueFrom": {"fieldRef": {"fieldPath": "metadata.name"}}})  # static membership
    mounts = [{"name": "tmp", "mountPath": "/tmp"}]
    if s.get("stateful"):
        mounts.append({"name": "state", "mountPath": "/var/lib/recs-streams"})
    if s.get("models"):
        mounts.append({"name": "models", "mountPath": "/models", "readOnly": True})
    probe = lambda path: {"httpGet": {"path": path, "port": "http"}, "periodSeconds": 10, "timeoutSeconds": 3}
    return {
        "name": name,
        "image": f"recsys/{name}:latest",
        "imagePullPolicy": "IfNotPresent",
        "ports": [{"name": "http", "containerPort": s["port"]}],
        "envFrom": COMMON_ENV_FROM,
        "env": env,
        "resources": {
            # No CPU limit: throttling hurts tail latency; memory limit = request (Guaranteed memory).
            "requests": {"cpu": s["cpu"], "memory": s["memory"]},
            "limits": {"memory": s["memory"]},
        },
        "startupProbe": {**probe("/actuator/health/liveness"), "failureThreshold": 30, "periodSeconds": 5},
        "livenessProbe": {**probe("/actuator/health/liveness"), "failureThreshold": 3},
        "readinessProbe": {**probe("/actuator/health/readiness"), "failureThreshold": 3},
        # Let endpoints/load balancers drop the pod before graceful shutdown starts.
        "lifecycle": {"preStop": {"exec": {"command": ["sleep", "10"]}}},
        "securityContext": {
            "runAsNonRoot": True,
            "runAsUser": 10001,
            "allowPrivilegeEscalation": False,
            "readOnlyRootFilesystem": True,
            "capabilities": {"drop": ["ALL"]},
            "seccompProfile": {"type": "RuntimeDefault"},
        },
        "volumeMounts": mounts,
    }


def workload(name, s):
    volumes = [{"name": "tmp", "emptyDir": {}}]
    if s.get("models"):
        volumes.append({"name": "models", "emptyDir": {}})  # filled by the model-sync sidecar (prod) / hostPath (local)
    pod = {
        "metadata": {"labels": labels(name), "annotations": {"prometheus.io/scrape": "true", "prometheus.io/port": str(s["port"]), "prometheus.io/path": "/actuator/prometheus"}},
        "spec": {
            "serviceAccountName": "recsys",
            # No docker-link env vars (KAFKA_PORT=tcp://… breaks the Kafka image; REDIS_PORT etc. could
            # collide with app config).
            "enableServiceLinks": False,
            "terminationGracePeriodSeconds": 45,
            "securityContext": {"fsGroup": 10001, "runAsNonRoot": True, "seccompProfile": {"type": "RuntimeDefault"}},
            "topologySpreadConstraints": [
                {"maxSkew": 1, "topologyKey": "topology.kubernetes.io/zone", "whenUnsatisfiable": "ScheduleAnyway", "labelSelector": {"matchLabels": labels(name)}},
                {"maxSkew": 1, "topologyKey": "kubernetes.io/hostname", "whenUnsatisfiable": "ScheduleAnyway", "labelSelector": {"matchLabels": labels(name)}},
            ],
            "containers": [container(name, s)],
            "volumes": volumes,
        },
    }
    spec = {"replicas": s["replicas"], "selector": {"matchLabels": labels(name)}, "template": pod}
    if s.get("stateful"):
        spec.update(
            serviceName=f"{name}-headless",
            podManagementPolicy="Parallel",
            updateStrategy={"type": "RollingUpdate"},
            volumeClaimTemplates=[{
                "metadata": {"name": "state"},
                "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": s["state_volume"]}}},
            }],
        )
        kind = "StatefulSet"
    else:
        spec["strategy"] = {"type": "RollingUpdate", "rollingUpdate": {"maxUnavailable": 0, "maxSurge": "25%"}}
        kind = "Deployment"
    return {"apiVersion": "apps/v1", "kind": kind, "metadata": {"name": name, "labels": labels(name)}, "spec": spec}


def service(name, s, headless=False):
    spec = {"selector": labels(name), "ports": [{"name": "http", "port": s["port"], "targetPort": "http"}]}
    if headless:
        spec["clusterIP"] = "None"
    return {"apiVersion": "v1", "kind": "Service", "metadata": {"name": f"{name}-headless" if headless else name, "labels": labels(name)}, "spec": spec}


def hpa(name, s):
    lo, hi, cpu = s["hpa"]
    return {
        "apiVersion": "autoscaling/v2",
        "kind": "HorizontalPodAutoscaler",
        "metadata": {"name": name},
        "spec": {
            "scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": name},
            "minReplicas": lo,
            "maxReplicas": hi,
            "metrics": [{"type": "Resource", "resource": {"name": "cpu", "target": {"type": "Utilization", "averageUtilization": cpu}}}],
            "behavior": {
                "scaleUp": {"stabilizationWindowSeconds": 0, "policies": [{"type": "Percent", "value": 100, "periodSeconds": 30}]},
                "scaleDown": {"stabilizationWindowSeconds": 300, "policies": [{"type": "Percent", "value": 20, "periodSeconds": 60}]},
            },
        },
    }


def pdb(name, s):
    return {"apiVersion": "policy/v1", "kind": "PodDisruptionBudget", "metadata": {"name": name},
            "spec": {"minAvailable": s["pdb"], "selector": {"matchLabels": labels(name)}}}


